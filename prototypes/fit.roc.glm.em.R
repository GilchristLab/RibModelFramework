## getarg: supports '--flag value' and '--flag=value'; returns def if the flag is
## absent OR its value is missing (last token, or the next token is another flag).
getarg <- function(flag, def){
  eqi <- grep(paste0("^", flag, "="), args, fixed=FALSE)
  if (length(eqi)) return(sub(paste0("^", flag, "="), "", args[eqi[1]]))
  i <- match(flag, args)
  if (is.na(i) || i+1 > length(args) || grepl("^--", args[i+1])) return(def)
  args[[i+1]]
}
