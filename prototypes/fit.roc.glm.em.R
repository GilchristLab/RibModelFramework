# ============================================================================
# Script:       fit.roc.glm.em.R
# Version:      0.8.0
# Created:      2026-06-17
# Revised:      2026-06-19
# Purpose:      Fit the ROC codon model as a multinomial GLMM by coordinate
#               ascent (IRLS-EM) -- a fast, deterministic alternative to native
#               MCMC. CSP step = per-AA multinomial logistic GLM (codon ~ phi);
#               phi step = per-gene analytic damped Fisher-scoring (the NB /
#               Poisson-Gamma update) + a median-gauged Gamma(sphi) prior (the
#               prior pins the scale, so no separate gauge step). Laplace SEs for
#               phi/dM/dEta. sphi (= SD log phi) is weakly identified from codon
#               data; --est-sphi profiles a proper ADAPTIVE GAUSS-HERMITE
#               marginal (integrates each gene's phi out; the single-point
#               Laplace marginal is artifactual and monotone -- both are reported
#               for comparison, plus the data-fit plateau cross-check). Default
#               is fixed --sphi. See notes/sphi-Ne-metrics-gamma-theory.md.
#
#               DATA: by default the script is SELF-CONTAINED -- it SIMULATES a
#               ROC genome from known dM/dEta/phi (like prototypes/phi_mixture.R)
#               and validates recovery against that truth. Pass --fasta + --deta
#               + --dM + --phi-ref to fit a real genome against external native
#               ROC references instead.
#
#               ROC log-odds linearity:  log P(codon c | gene g)/P(ref) =
#               dM_c + dEta_c * phi_g  -> given phi it is a multinomial GLM,
#               given the GLM it is a per-gene 1-D solve.
#
# Usage:        Rscript fit.roc.glm.em.R [--sphi N] [--est-sphi T/F] [--png F]
#                 simulate (default): [--n-genes N] [--sim-sphi N] [--seed N]
#                                     [--sim-phi-dist gamma|lognormal]
#                 real data:          [--fasta F] [--deta CSV] [--dM CSV] [--phi-ref CSV]
#                 common:             [--lib DIR] [--verbose T/F] [--dry-run] [--help]
