#               is fixed --sphi. See notes/sphi-Ne-metrics-gamma-theory.md.
#
#               ROC log-odds linearity:  log P(codon c | gene g)/P(ref) =
#               dM_c + dEta_c * phi_g  -> given phi it is a multinomial GLM,
#               given the GLM it is a per-gene 1-D solve.
#
