usage <- function(){
  cat("Usage: Rscript fit.roc.glm.em.R [--sphi N] [--est-sphi T/F] [--png F]\n",
      "  simulate (default): [--n-genes N] [--sim-sphi N] [--seed N] [--sim-phi-dist gamma|lognormal]\n",
      "  real data:          [--fasta F] [--deta CSV] [--dM CSV] [--phi-ref CSV]\n",
      "  common:             [--lib DIR] [--verbose T/F] [--dry-run] [--help]\n",
      "Default mode SIMULATES a ROC genome and validates recovery vs the known\n",
      "truth; pass --fasta to fit a real genome instead. See the script header.\n", sep="")
}

main <- function(){
  args <- commandArgs(TRUE)
  has.flag <- function(flag) flag %in% args
  getarg <- function(flag, def){
    eqi <- grep(paste0("^", flag, "="), args)
    if (length(eqi)) return(sub(paste0("^", flag, "="), "", args[eqi[1]]))
    i <- match(flag, args)
    if (is.na(i) || i+1 > length(args) || grepl("^--", args[i+1])) return(def)
    args[[i+1]]
  }
  parse_logical <- function(flag, def){
    v <- getarg(flag, def); lv <- tolower(as.character(v))
    if (lv %in% c("t","true","1","yes","y"))  return(TRUE)
    if (lv %in% c("f","false","0","no","n")) return(FALSE)
    stop(sprintf("%s expects a logical (T/F/TRUE/FALSE/1/0/yes/no); got '%s'", flag, v), call.=FALSE)
  }
  parse_num <- function(flag, def){
    v <- getarg(flag, def); n <- suppressWarnings(as.numeric(v))
    if (is.na(n)) stop(sprintf("%s expects a number; got '%s'", flag, v), call.=FALSE)
    n
  }
  if (has.flag("--help") || has.flag("-h")) { usage(); quit(save="no", status=0) }

  lib      <- getarg("--lib", "~/R/lib/main-a664454")
  sphi.fix <- parse_num("--sphi", "1.4")   # canonical fixed-sphi gauge (benchmarks)
  est.sphi <- parse_logical("--est-sphi", "FALSE")
  verbose  <- parse_logical("--verbose", "TRUE")
  dry.run  <- has.flag("--dry-run")
  png.out  <- getarg("--png", "/tmp/roc_glm_em.png")
  ## real-data mode is triggered by --fasta; otherwise simulate (self-contained)
  fasta    <- getarg("--fasta", NA)
  real     <- !is.na(fasta)
  n.genes  <- as.integer(parse_num("--n-genes", "500"))
  sim.sphi <- parse_num("--sim-sphi", "1.4")
  seed     <- as.integer(parse_num("--seed", "1"))
  sim.dist <- getarg("--sim-phi-dist", "gamma")     # 'gamma' (GLMM) or 'lognormal' (native/Stan)

  if (real){
    deta.f  <- getarg("--deta",  NA); dM.f <- getarg("--dM", NA); phi.ref <- getarg("--phi-ref", NA)
    in.files <- c(fasta=fasta, deta=deta.f, dM=dM.f, "phi-ref"=phi.ref)
    if (anyNA(in.files)) stop("real-data mode (--fasta given) requires --deta, --dM and --phi-ref too", call.=FALSE)
    miss <- in.files[!file.exists(path.expand(in.files))]
    if (length(miss)) stop(sprintf("missing input file(s):\n%s",
        paste(sprintf("  --%s : %s", names(miss), miss), collapse="\n")), call.=FALSE)
  }
  if (dry.run){
    cat(sprintf("DRY RUN -- mode=%s  sphi.fix=%g  est.sphi=%s  verbose=%s  png=%s\n",
                if (real) "real" else "simulate", sphi.fix, est.sphi, verbose, png.out))
    if (real) for (nm in names(in.files)) cat(sprintf("  %-8s %s\n", nm, in.files[nm]))
    else cat(sprintf("  simulate: n.genes=%d  sim.sphi=%g  phi.dist=%s  seed=%d\n", n.genes, sim.sphi, sim.dist, seed))
    quit(save="no", status=0)
  }

  .libPaths(c(path.expand(lib), .libPaths()))
  suppressPackageStartupMessages(library(VGAM))

  if (real){
    cat(sprintf("REAL-DATA mode: %s\n", fasta))
    data <- prepare_genome_from_files(fasta, deta.f, dM.f)
    res  <- fit_roc_glm_em(data, sphi.fix, est.sphi, verbose=verbose)
    ref  <- read.csv(phi.ref)
    report_and_plot(res,
      ref.dM     = setNames(data$dMt$Mean, data$dMt$Codon),
      ref.dEta   = setNames(data$det$Mean, data$det$Codon),
      ref.logphi = setNames(ref$log_phi, ref$gene_id),
      ref.sphi.sd= sd(ref$log_phi), ref.label="native ROC fit", png.out=png.out)
  } else {
    cat(sprintf("SIMULATE mode: n.genes=%d  sim.sphi=%g  phi.dist=%s  seed=%d\n",
                n.genes, sim.sphi, sim.dist, seed))
    data <- simulate_roc_genome(n.genes=n.genes, sphi=sim.sphi, seed=seed, phi.dist=sim.dist)
    res  <- fit_roc_glm_em(data, sphi.fix, est.sphi, verbose=verbose)
    tr   <- data$truth
    report_and_plot(res,
      ref.dM     = tr$dM, ref.dEta = tr$dEta,
      ref.logphi = setNames(log(tr$phi), names(tr$phi)),
      ref.sphi.sd= sd(log(tr$phi)), ref.label=sprintf("truth (%s phi)", tr$phi.dist), png.out=png.out)
  }
}

if (sys.nframe() == 0L) main()
