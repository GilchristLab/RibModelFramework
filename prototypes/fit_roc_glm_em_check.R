# Purpose:      Recovery check for the ROC GLM-EM fitter (prototypes/fit.roc.glm.em.R).
#               Sources that file (functions only -- its main() is guarded), then
#               simulates ROC genomes from KNOWN dM/dEta/phi and verifies the fit
#               recovers them. Run under BOTH phi priors:
#                 - gamma      : matches the GLMM's own prior
#                 - lognormal  : matches native MCMC / Stan
#               so it also demonstrates that recovery is ROBUST to the phi-prior
#               shape mismatch (the codon<->phi multinomial-logit relation is
#               prior-agnostic; the prior only weakly regularises phi).
#
# Usage:        Rscript fit_roc_glm_em_check.R          (run from anywhere)
# Output:       stdout: a recovery table; stops with non-zero status on FAIL.
#
# Requirements: VGAM (same as the fitter).
#
