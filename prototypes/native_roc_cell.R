# Purpose:      Native AnaCoDa ROC MCMC cell for the cross-backend recovery
#               comparison. Simulates a ROC genome from known truth (dM,
#               dEta, phi) using AnaCoDa's model$simulateGenome, fits it
#               with native MCMC, then extracts dM/dEta/phi and reports
#               recovery correlations vs. the known truth.
#
#               Truth extraction strategy (A): initializeParameterObject
#               draws random dM/dEta from ROC priors and phi from a
#               lognormal(0, sphi) distribution. The drawn values are
#               extracted BEFORE simulateGenome via:
#                 - parameter$currentMutationParameter  -> dM (list[[1]])
#                 - parameter$currentSelectionParameter -> dEta (list[[1]])
#                 - parameter$getCurrentSynthesisRateForMixture(FALSE) -> phi
#               These are the EXACT values used by simulateGenome, so they
#               are ground truth with no setter calls needed.
#
#               Codon ordering: parameter$getGroupList() returns the 19 AA
#               groups; AAToCodon(aa, TRUE) gives the non-reference codons
#               in the same order as the parameter flat vector.
#
#               Recovery metrics (matched convention):
#                 dM, dEta: Pearson r vs. truth (same sign convention)
#                 phi:      Pearson r on log(phi) + Spearman rho
#
# Usage:        Rscript prototypes/native_roc_cell.R [--seed N] [--samples N]
#                       [--thinning N] [--lib PATH] [--help]
#
#               Or source() and call native_roc_recovery(seed, samples, thinning)
#               directly -- the main() block is guarded by sys.nframe()==0.
#
# Input:        tests/testthat/UnitTestingData/testMCMCROCFiles/
#                 simulatedAllUniqueR.fasta (1000-gene template; used only for
#                 gene lengths -- sequences are replaced by simulateGenome)
#
# Output:       Stdout: convergence log + one-line recovery summary
#               Return: named vector c(phi.spS, dEta, dM)
#
# Requirements:
#   - AnaCoDa installed at ~/R/lib/main-a664454 (or --lib override)
#   - Run with: OMP_NUM_THREADS=1 nice -n 19 Rscript ...
#
# Session:      ROC cross-backend comparison (native cell)
